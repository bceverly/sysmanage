"""
The Phase 23.3 skew proof, end to end, on a throwaway VM.

  1. CREATE a VM (Vagrant + libvirt, the screenshot pipeline's toolchain)
     with chrony (or systemd-timesyncd) as its time service;
  2. INSTALL the agent from your working tree (``--agent-src``), running as
     root so it is privileged, pointed at ``--server``;
  3. wait for it to REGISTER, APPROVE it, and wait for its first clock
     measurement in bounds;
  4. RUN ``clock_skew_proof.py`` against it (time service stopped, clock set
     ``--skew`` seconds ahead, measured, critical, [alert], resynced, back in
     bounds, [alert resolved]);
  5. CAPTURE everything into ``--results/<UTC timestamp>/``: the proof's
     output, the agent's journal, the host's clock before and after, its
     resyncs, the VM's own view of its clock, and a SUMMARY;
  6. TEAR DOWN -- always, pass or fail or Ctrl-C: the host is deleted from
     the server and the VM destroyed (``--keep`` keeps both for debugging).

Usage:
    python3 scripts/clock_skew_vm_test.py --server https://sysmanage.lan \\
        [--agent-server sysmanage.lan:443] [--enrollment-token TOKEN] \\
        [--time-service chrony|timesyncd] [--skew 120] [--expect-alert]

Credentials as for the proof: ``--token`` / SYSMANAGE_TOKEN, or SYSMANAGE_USER
+ SYSMANAGE_PASSWORD (the user needs Approve Host Registration, Resync Host
Clock and Delete Host).  ``--insecure`` for a lab server's self-signed
certificate.  The VM reaches the server through the libvirt NAT, i.e. through
whatever this machine can reach.

Exit status: the proof's (0 proven, 1 not proven), or 2 when the harness
itself could not get as far as running it.
"""

