TIME_SERVICES = {
    # Ubuntu's default is timesyncd; chrony replaces it (and exercises the
    # stopped-chronyd resync path, `chronyd -q`).
    "chrony": ("chrony", "systemctl enable --now chrony"),
    "timesyncd": ("systemd-timesyncd", "systemctl enable --now systemd-timesyncd"),
}


def log(results: Path, message: str) -> None:
    line = f"[{datetime.now(timezone.utc).strftime('%H:%M:%S')}] {message}"
    print(line, flush=True)
    with open(results / "harness.log", "a", encoding="utf-8") as handle:
        handle.write(line + "\n")


def run(cmd, cwd, results: Path, logname: str, timeout=1800, check=True):
    """Run a fixed argv, its output appended to ``results/logname``.

    In its own process group, and the whole group is killed on a timeout:
    ``vagrant`` is a wrapper around ruby, and killing only the wrapper left
    ruby running -- still holding the machine's lock, so the teardown's
    ``vagrant destroy`` was refused and the VM outlived the harness."""
    with open(results / logname, "a", encoding="utf-8") as out:
        out.write(f"\n$ {' '.join(cmd)}\n")
        out.flush()
        # pylint: disable-next=consider-using-with  # waited on/killed below
        proc = subprocess.Popen(  # nosec B603
            cmd, cwd=cwd, stdout=out, stderr=subprocess.STDOUT,
            start_new_session=True,
        )  # fmt: skip
        try:
            returncode = proc.wait(timeout=timeout)
        except subprocess.TimeoutExpired:
            _kill_group(proc)
            raise RuntimeError(
                f"{cmd[0]} {cmd[1]} did not finish in {timeout} s (see {logname})"
            ) from None
        except BaseException:
            # Ctrl-C: the new session does not get the terminal's SIGINT.
            _kill_group(proc)
            raise
    if check and returncode != 0:
        raise RuntimeError(f"{cmd[0]} {cmd[1]} failed (see {logname})")
    return returncode


def _kill_group(proc) -> None:
    for sig in (signal.SIGTERM, signal.SIGKILL):
        try:
            os.killpg(proc.pid, sig)
        except ProcessLookupError:
            return
        try:
            proc.wait(timeout=15)
            return
        except subprocess.TimeoutExpired:
            continue


def capture(cmd, cwd, timeout=120, stderr=True) -> str:
    proc = subprocess.run(  # nosec B603
        cmd, cwd=cwd, capture_output=True, text=True, timeout=timeout, check=False
    )
    return proc.stdout + (proc.stderr if stderr else "")


def agent_endpoint(args):
    if args.agent_server:
        host, _, port = args.agent_server.rpartition(":")
        if not host or not port.isdigit():
            sys.exit("--agent-server must be host:port.")
        return host, int(port), args.agent_https
    url = urlparse(args.server)
    https = url.scheme == "https"
    return url.hostname, url.port or (443 if https else 80), https


def write_vm(workdir: Path, args, hostname: str) -> None:
    host, port, https = agent_endpoint(args)
    pkg, setup = TIME_SERVICES[args.time_service]
    security = ""
    if args.enrollment_token:
        security = f'security:\n  enrollment_token: "{args.enrollment_token}"\n'
    (workdir / "Vagrantfile").write_text(
        VAGRANTFILE.format(
            box=args.box,
            hostname=hostname,
            prefix=f"{hostname}-",
            agent_src=str(args.agent_src),
            exclude=RSYNC_EXCLUDE,
        )
    )
    (workdir / "provision.sh").write_text(
        PROVISION.format(
            time_pkg=pkg,
            time_setup=setup,
            server_host=host,
            server_port=port,
            use_https="true" if https else "false",
            security=security,
        )
    )


def wait_for(results, what, probe, timeout, interval=10):
    log(results, f"waiting for {what} (up to {timeout} s)")
    deadline = time.monotonic() + timeout
    while time.monotonic() < deadline:
        found = probe()
        if found:
            return found
        time.sleep(interval)
    return None


def registered_host(args, token, hostname):
    status, hosts = proof._request(args.server, "GET", "/hosts", token)
    if status != 200 or not isinstance(hosts, list):
        return None
    for host in hosts:
        if (host.get("fqdn") or "").split(".")[0] == hostname:
            return host
    return None


def bring_up(args, token, workdir, results, hostname):
    """Create, register, approve, measure.  Returns the host, or None."""
    log(results, f"creating VM {hostname} ({args.box}, {args.time_service})")
    # Boot and provision separately, each with its own limit, so a hang says
    # which half it was in.  provision.sh prints "=== [n/6] ... ===" per step.
    run(
        ["vagrant", "up", "--provider=libvirt", "--no-provision"],
        workdir, results, "vagrant.log", timeout=900,
    )  # fmt: skip
    log(results, "VM up; provisioning (see vagrant.log for the step)")
    run(["vagrant", "provision"], workdir, results, "vagrant.log", timeout=2400)
    log(results, "provisioned")
    # stdout only: vagrant-libvirt's fog prints "[fog][WARNING] ..." on stderr,
    # which in the file made ssh refuse the whole config.
    (workdir / "ssh_config").write_text(
        capture(["vagrant", "ssh-config"], workdir, stderr=False)
    )
    host = wait_for(
        results, "the agent to register",
        lambda: registered_host(args, token, hostname), args.register_timeout,
    )  # fmt: skip
    if host is None:
        log(results, "the agent never registered -- see agent-journal.log")
        return None
    log(results, f"registered as {host['fqdn']} ({host.get('approval_status')})")
    if host.get("approval_status") != "approved":
        status, _ = proof._request(
            args.server, "PUT", f"/host/{host['id']}/approve", token
        )
        if status != 200:
            log(results, f"approving the host failed (HTTP {status})")
            return None
        log(results, "approved")

    def ready():
        # Measured in bounds AND its time service reported: the proof stops
        # that service, and the report comes with the agent's periodic data
        # collection, after the first measurement.
        clock = proof._clock(args.server, token, host["id"])
        if not clock or clock.get("status") != "ok":
            return None
        return clock if (clock.get("time_service") or {}).get("service") else None

    clock = wait_for(
        results, "a clock measurement in bounds and the time service", ready, 900
    )
    if clock is None:
        log(results, "the host was never measured in bounds with its time service")
        return None
    (results / "clock-before.json").write_text(json.dumps(clock, indent=2))
    return host


def collect(args, token, workdir, results, host):
    """Everything worth keeping, before the VM goes."""
    if host is not None:
        clock = proof._clock(args.server, token, host["id"])
        (results / "clock-after.json").write_text(json.dumps(clock, indent=2))
        _s, resyncs = proof._request(
            args.server, "GET", f"/time-sync/resyncs?host_id={host['id']}", token
        )
        (results / "resyncs.json").write_text(json.dumps(resyncs, indent=2))
    if (workdir / ".vagrant").exists():
        ssh = ["vagrant", "ssh", "-c"]
        (results / "agent-journal.log").write_text(
            capture(ssh + ["sudo journalctl -u sysmanage-agent --no-pager"], workdir)
        )
        # The agent logs to its own file, not the journal.
        (results / "agent.log").write_text(
            capture(
                ssh + ["sudo cat /var/log/sysmanage-agent/agent.log"],
                workdir,
                stderr=False,
            )
        )
        (results / "vm-clock.txt").write_text(
            capture(
                ssh + ["date -u; timedatectl; chronyc tracking 2>&1 || true"], workdir
            )
        )


def tear_down(args, token, workdir, results, host, hostname):
    if args.keep:
        log(results, f"--keep: leaving the VM ({workdir}) and the host on the server")
        return
    if host is not None:
        status, _ = proof._request(args.server, "DELETE", f"/host/{host['id']}", token)
        log(results, f"deleted the host from the server (HTTP {status})")
    if not (workdir / "Vagrantfile").exists():
        return
    try:
        rc = run(
            ["vagrant", "destroy", "-f"], workdir, results, "vagrant.log",
            timeout=300, check=False,
        )  # fmt: skip
    except RuntimeError:
        rc = None
    if rc != 0:
        rc = destroy_with_virsh(results, domain_name(hostname))
    if rc == 0:
        log(results, "destroyed the VM")
        shutil.rmtree(workdir, ignore_errors=True)
    else:
        log(
            results,
            f"COULD NOT DESTROY the VM -- remove it by hand: virsh -c {LIBVIRT_URI} "
            f"destroy {domain_name(hostname)}; virsh -c {LIBVIRT_URI} undefine "
            f"{domain_name(hostname)} --remove-all-storage",
        )


def domain_name(hostname: str) -> str:
    """The libvirt domain (``default_prefix`` + the machine name)."""
    return f"{hostname}-default"


def destroy_with_virsh(results, domain) -> int:
    """The fallback when vagrant cannot destroy its own VM."""
    if shutil.which("virsh") is None:
        return 1
    log(results, f"vagrant could not destroy the VM; trying virsh on {domain}")
    virsh = ["virsh", "-c", LIBVIRT_URI]
    capture(virsh + ["destroy", domain], None)
    out = capture(virsh + ["undefine", domain, "--remove-all-storage"], None)
    gone = "failed to get domain" in capture(virsh + ["dominfo", domain], None)
    with open(results / "vagrant.log", "a", encoding="utf-8") as handle:
        handle.write(out)
    return 0 if gone else 1


def run_proof(args, workdir, results, host) -> int:
    cmd = [
        sys.executable, str(HERE / "clock_skew_proof.py"),
        "--server", args.server, "--host", host["fqdn"],
        "--ssh", "default", "--ssh-config", str(workdir / "ssh_config"),
        "--skew", str(args.skew), "--timeout", str(args.timeout),
    ]  # fmt: skip
    if args.expect_alert:
        cmd.append("--expect-alert")
    if args.insecure:
        cmd.append("--insecure")
    log(results, "running the proof")
    env = dict(os.environ)
    if args.token:
        env["SYSMANAGE_TOKEN"] = args.token
    proc = subprocess.run(  # nosec B603
        cmd, capture_output=True, text=True, env=env, check=False,
        timeout=args.timeout * 5,
    )  # fmt: skip
    output = proc.stdout + proc.stderr
    (results / "proof.log").write_text(output)
    print(output, flush=True)
    return proc.returncode


def parse_args():
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument(
        "--server", required=True, help="the API URL, e.g. https://sysmanage.lan"
    )
    parser.add_argument(
        "--agent-server", help="host:port the AGENT connects to (default: --server's)"
    )
    parser.add_argument(
        "--agent-https", action="store_true", help="with --agent-server: TLS"
    )
    parser.add_argument("--enrollment-token", help="for a multi-tenant server")
    parser.add_argument("--agent-src", type=Path, default=DEFAULT_AGENT_SRC)
    parser.add_argument("--box", default="generic/ubuntu2204")
    parser.add_argument(
        "--time-service", choices=sorted(TIME_SERVICES), default="chrony"
    )
    parser.add_argument("--skew", type=float, default=120.0)
    parser.add_argument("--timeout", type=int, default=600)
    parser.add_argument("--register-timeout", type=int, default=900)
    parser.add_argument("--expect-alert", action="store_true")
    parser.add_argument("--results", type=Path, default=Path("clock-skew-results"))
    parser.add_argument("--keep", action="store_true", help="keep the VM and the host")
    parser.add_argument("--token", default=os.environ.get("SYSMANAGE_TOKEN"))
    parser.add_argument("--insecure", action="store_true")
    return parser.parse_args()  # fmt: skip


def main() -> int:
    args = parse_args()
    if not args.server.lower().startswith(("https://", "http://")):
        sys.exit("--server must be an http:// or https:// URL.")
    if not (args.agent_src / "main.py").is_file():
        sys.exit(f"--agent-src: no agent at {args.agent_src}")
    for tool in ("vagrant", "ssh"):
        if shutil.which(tool) is None:
            sys.exit(f"{tool} is not installed.")
    if args.insecure:
        # nosemgrep
        proof._CONTEXT = proof.ssl._create_unverified_context()  # nosec B323
    token = args.token or proof._login(args.server)
    stamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")
    results = (args.results / stamp).resolve()
    results.mkdir(parents=True)
    workdir = results / "vm"
    workdir.mkdir()
    hostname = f"skewtest-{secrets.token_hex(3)}"
    write_vm(workdir, args, hostname)

    host, code, reason = None, 2, "the harness stopped before the proof ran"
    try:
        host = bring_up(args, token, workdir, results, hostname)
        if host is not None:
            code = run_proof(args, workdir, results, host)
            reason = {0: "PROVEN", 1: "NOT PROVEN"}.get(code, f"proof exited {code}")
    except KeyboardInterrupt:
        reason = "interrupted"
    except Exception as exc:  # pylint: disable=broad-exception-caught
        reason = f"harness error: {exc}"
        log(results, reason)
    finally:
        try:
            collect(args, token, workdir, results, host)
        finally:
            tear_down(args, token, workdir, results, host, hostname)
    summary = (
        f"Clock skew proof -- {stamp}\n"
        f"result:       {reason}\n"
        f"server:       {args.server}\n"
        f"vm:           {hostname} ({args.box}, {args.time_service})\n"
        f"skew:         +{args.skew:g} s\n"
        f"expect alert: {args.expect_alert}\n"
        f"artifacts:    {results}\n"
    )
    (results / "SUMMARY.txt").write_text(summary)
    print("\n" + summary)
    return code


if __name__ == "__main__":
    sys.exit(main())
